#!/usr/bin/env node
// Lists the image files that really exist under /public/images.
//
// The database points every dish at /public/images/products/<slug>.jpg, but
// the owner uploads those photos one by one. Asking the browser for a photo
// that is not there gives a broken image and a 404 in the console, so the
// storefront checks this list first and draws the flat pistachio tile instead.
//
// Usage: node scripts/build-image-manifest.mjs
// Writes: src/storefront/data/imageManifest.js

import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const IMAGES_DIR = join(ROOT, 'public', 'images');
const OUT_FILE = join(ROOT, 'src', 'storefront', 'data', 'imageManifest.js');

const EXTENSIONS = ['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif', '.svg'];

function walk(dir, out = []) {
  let entries = [];
  try {
    entries = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of entries) {
    const full = join(dir, name);
    let info;
    try {
      info = statSync(full);
    } catch {
      continue;
    }
    if (info.isDirectory()) walk(full, out);
    else if (EXTENSIONS.includes(name.slice(name.lastIndexOf('.')).toLowerCase())) out.push(full);
  }
  return out;
}

const files = walk(IMAGES_DIR)
  .map((file) => `/images/${relative(IMAGES_DIR, file).split(sep).join('/')}`)
  .sort();

const body = `// Generated by scripts/build-image-manifest.mjs - do not edit by hand.
// Every image file that really exists under /public/images. The storefront
// checks a photo against this list before it asks the browser to load it, so a
// photo that has not been uploaded yet turns into the flat pistachio tile
// instead of a broken image.
export const LOCAL_IMAGE_FILES = [
${files.map((file) => `  '${file}',`).join('\n')}
];
`;

writeFileSync(OUT_FILE, body, 'utf8');
console.log(`image-manifest: ${files.length} file(s) listed.`);
